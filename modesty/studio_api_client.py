"""Generated-schema Studio API v1 client for deterministic Modesty operations.

The operation registry is generated by tools/generate_studio_api_client.py.
OAuth is deliberately owned by the injected server transport: credentials never
enter UI request bodies or this client's operation/cache data. There is no MCP
fallback and no automatic write retry, including after a revision conflict.
"""
from copy import deepcopy
from dataclasses import dataclass, field
import json
import hashlib
import math
from pathlib import Path
import re
import threading
from typing import Any, Dict, Optional
from urllib.parse import quote, unquote, urlencode, urlsplit
import uuid

BASE_URL = "https://freestyle.audio/api/v1"
DEFAULT_MANIFEST = Path(__file__).with_name("studio_api_operations.json")
MUTATIONS = {"POST", "PUT", "PATCH", "DELETE"}
# Operations whose 200 body is binary. The transport returns bytes as data; a
# 304 is a normal "unchanged" result with no body and is never cached here.
BINARY_OPERATIONS = {"getPluginEditorFrame": "image/jpeg"}
# Live editor input: each event is sent once. It is neither retained for replay
# nor resendable (a duplicate pointer phase could double-click a native GUI).
NON_RETRYING_OPERATIONS = frozenset({"sendPluginEditorPointer", "sendPluginEditorScroll", "sendPluginEditorKeys"})
# Live mix revision domain (ETag "mix-<n>" / body expected_mix_revision). It is
# separate from the timeline: a mix guard is sent only when the caller passes
# one (If-Match or expected_mix_revision); a cached mix ETag is never attached
# implicitly, because anyone (a Studio fader) may move the mix at any time.
MIX_OPERATIONS = frozenset({"getEngineMix", "waitEngineMix", "applyEngineMix", "setLaneGain", "setLanePan", "setLaneMute",
                            "setLaneSolo", "setLaneRouting", "setMasterGain", "setBusGain", "setBusMute", "setBusSolo",
                            "setBusPan", "setMasterPan"})
# Writes outside the timeline domain that still bump the project's timeline
# revision without returning it as a timeline ETag (339-op spec: sample edits
# return the SOURCE revision as ETag; addAudioFromUrl adds a lane + take).
# updateLane with a mix guard runs in the mix domain but also saves the lane row.
TIMELINE_SIDE_EFFECT_OPERATIONS = frozenset({"editClipSamples", "undoClipSampleEdit", "addAudioFromUrl", "updateLane"})
# Long-poll reads whose 304 means "unchanged" (no cached body is substituted).
UNCHANGED_304_OPERATIONS = frozenset({"waitEngineMix"})


def mix_etag(revision):
    """expected_mix_revision n <-> If-Match "mix-<n>"."""
    if isinstance(revision, bool) or not isinstance(revision, int) or revision < 0:
        raise StudioApiPlanningError("A mix revision is a nonnegative integer.")
    return '"mix-{}"'.format(revision)


class StudioApiPlanningError(ValueError):
    """A request was refused locally, before any network dispatch."""
    def __init__(self, message, code="studio_request_planning_error"):
        super().__init__(message)
        self.code = code


@dataclass(frozen=True)
class StudioApiRequest:
    operation_id: str
    method: str
    url: str
    headers: Dict[str, str]
    body: Any = None
    revision_domain: Any = None
    cache_epoch: int = 0
    serial: int = 0


@dataclass
class StudioApiResponse:
    status: int
    data: Any
    headers: Dict[str, str] = field(default_factory=dict)
    from_cache: bool = False

    def header(self, name, default=None):
        return next((value for key, value in self.headers.items() if key.lower() == name.lower()), default)


class StudioApiError(Exception):
    """The API's error envelope, real HTTP status and original request."""
    def __init__(self, response, request):
        data = response.data if isinstance(response.data, dict) else {}
        error = data.get("error")
        error = error if isinstance(error, dict) else {}
        self.status = response.status
        self.code = error.get("code") or "studio_http_{}".format(response.status)
        self.message = error.get("message") or "Freestyle Studio API returned HTTP {}.".format(response.status)
        self.stage = error.get("stage")
        self.engine_status = error.get("engineStatus")
        self.engineStatus = self.engine_status
        self.details = deepcopy(error.get("details"))
        self.request_id = error.get("requestId") or response.header("X-Request-Id")
        self.requestId = self.request_id
        self.headers = dict(response.headers)
        self.data = deepcopy(response.data)
        self.request = request
        super().__init__(self.message)

    def envelope(self):
        error = {"code": self.code, "message": self.message}
        for name, value in (("stage", self.stage), ("engineStatus", self.engine_status),
                            ("details", self.details), ("requestId", self.request_id)):
            if value is not None:
                error[name] = deepcopy(value)
        return {"error": error}


def _header(headers, name):
    return next((value for key, value in headers.items() if key.lower() == name.lower()), None)


def _set_header(headers, name, value):
    if not isinstance(value, str) or not value or "\r" in value or "\n" in value:
        raise StudioApiPlanningError("{} must be a nonempty single-line header.".format(name))
    for existing in list(headers):
        if existing.lower() == name.lower():
            del headers[existing]
    headers[name] = value


def _etag(value):
    if isinstance(value, bool) or not isinstance(value, (str, int)):
        raise StudioApiPlanningError("A revision must be an integer or an opaque ETag.")
    value = str(value)
    if not value or "\r" in value or "\n" in value:
        raise StudioApiPlanningError("A revision must be a nonempty single-line ETag.")
    return value if value == "*" or value.startswith('"') or value.startswith('W/"') else '"{}"'.format(value.replace('"', '\\"'))


def _revision_value(value):
    value = str(value)
    if value.startswith("W/"):
        value = value[2:]
    return value[1:-1] if value.startswith('"') and value.endswith('"') else value


class StudioApiClient:
    """Plan spec-defined requests and call an injected synchronous transport.

    transport(request) returns StudioApiResponse(status, parsed_json, headers).
    Retain a StudioApiRequest and call send(request) to retry that exact intent;
    its Idempotency-Key and If-Match remain unchanged. Repeating call() with the
    same key and input also retains that original plan, including its revision.
    Nothing automatically retries a 4xx/5xx or a transport exception. At most
    4096 write intents are retained per client lifecycle; capacity rejects new
    intents rather than forgetting unresolved or previously completed keys.
    """
    def __init__(self, transport=None, *, base_url=BASE_URL, manifest=None, write_plan_limit=4096):
        parsed = urlsplit(base_url)
        if parsed.scheme not in ("http", "https") or not parsed.hostname or parsed.username or parsed.password or parsed.query or parsed.fragment:
            raise ValueError("Use an HTTP(S) API base URL without credentials, query or fragment.")
        self.base_url = base_url.rstrip("/")
        self.manifest = deepcopy(manifest) if manifest is not None else json.loads(DEFAULT_MANIFEST.read_text())
        self.operations = self.manifest["operations"]
        self.components = self.manifest.get("components", {})
        self.transport = transport
        self.etags = {}
        self._cache = {}
        self._epochs = {}
        self._pending_writes = {}
        self._observation_serial = {}
        self._serial = 0
        self._lock = threading.RLock()
        if type(write_plan_limit) is not int or write_plan_limit < 1:
            raise ValueError("Use a positive retained write-plan limit.")
        self._write_plan_limit = write_plan_limit
        self._write_plans = {}
        self._sent_inputs = {}
        self._timeline_stale = set()

    def inherit_retained_requests(self, previous):
        """Share the intent ledger across a schema refresh, before publication.

        The old planner may still have an in-flight request. Sharing its lock
        and ledger keeps that request and subsequent explicit recovery bound
        to the same original plan; authentication remains runtime-owned.
        """
        if not isinstance(previous, StudioApiClient) or self.base_url != previous.base_url:
            raise StudioApiPlanningError("Retained requests require the same Studio API endpoint.")
        with previous._lock:
            if self._write_plans and self._write_plans is not previous._write_plans:
                raise StudioApiPlanningError("A nonempty retained request ledger cannot be replaced.")
            self._lock = previous._lock
            self._write_plans = previous._write_plans
            self._write_plan_limit = previous._write_plan_limit
            self._sent_inputs = previous._sent_inputs
            self._timeline_stale = previous._timeline_stale
        return self

    def operation(self, operation_id):
        try:
            return self.operations[operation_id]
        except KeyError:
            raise StudioApiPlanningError("Unknown Studio API operation: {}".format(operation_id)) from None

    def _resolve(self, schema):
        if not isinstance(schema, dict):
            return schema
        if "$ref" not in schema:
            return schema
        ref = schema["$ref"]
        if not ref.startswith("#/components/"):
            raise StudioApiPlanningError("Only bundled OpenAPI component references are supported.")
        value = {"components": self.components}
        try:
            for key in ref[2:].split("/"):
                value = value[key.replace("~1", "/").replace("~0", "~")]
        except (KeyError, TypeError):
            raise StudioApiPlanningError("Unresolved generated schema reference: {}".format(ref)) from None
        return dict(value, **{key: item for key, item in schema.items() if key != "$ref"})

    def validate(self, value, schema, label="value", depth=0):
        """Validate published scalar/shape bounds without adding schema guesses."""
        if depth > 64:
            raise StudioApiPlanningError("{} is too deeply nested.".format(label))
        schema = self._resolve(schema)
        if schema is True or schema == {}:
            return
        if schema is False:
            raise StudioApiPlanningError("{} is not allowed.".format(label))
        if not isinstance(schema, dict):
            return
        for branch in schema.get("allOf", []):
            self.validate(value, branch, label, depth + 1)
        for kind in ("anyOf", "oneOf"):
            if kind in schema:
                matches = 0
                for branch in schema[kind]:
                    try:
                        self.validate(value, branch, label, depth + 1)
                        matches += 1
                    except StudioApiPlanningError:
                        pass
                if not matches or kind == "oneOf" and matches != 1:
                    raise StudioApiPlanningError("{} does not match its published schema.".format(label))
        types = schema.get("type")
        types = [types] if isinstance(types, str) else types
        tests = {"null": lambda: value is None,
                 "string": lambda: isinstance(value, str),
                 "boolean": lambda: isinstance(value, bool),
                 "integer": lambda: isinstance(value, int) and not isinstance(value, bool),
                 "number": lambda: isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value),
                 "object": lambda: isinstance(value, dict), "array": lambda: isinstance(value, list)}
        if types and not any(tests.get(kind, lambda: True)() for kind in types):
            raise StudioApiPlanningError("{} has the wrong type.".format(label))
        if "enum" in schema and value not in schema["enum"]:
            raise StudioApiPlanningError("{} is not a supported value.".format(label))
        if "const" in schema and value != schema["const"]:
            raise StudioApiPlanningError("{} does not match its required value.".format(label))
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            if not math.isfinite(value):
                raise StudioApiPlanningError("{} must be finite.".format(label))
            for key, failed in (("minimum", lambda bound: value < bound), ("maximum", lambda bound: value > bound),
                                ("exclusiveMinimum", lambda bound: value <= bound), ("exclusiveMaximum", lambda bound: value >= bound)):
                if key in schema and failed(schema[key]):
                    raise StudioApiPlanningError("{} exceeds its published {}.".format(label, key))
        if isinstance(value, str):
            if len(value) < schema.get("minLength", 0) or len(value) > schema.get("maxLength", math.inf):
                raise StudioApiPlanningError("{} exceeds its published string length.".format(label))
            if "pattern" in schema and re.search(schema["pattern"], value) is None:
                raise StudioApiPlanningError("{} does not match its published format.".format(label))
        if isinstance(value, list):
            if len(value) < schema.get("minItems", 0) or len(value) > schema.get("maxItems", math.inf):
                raise StudioApiPlanningError("{} exceeds its published item count.".format(label))
            for index, item in enumerate(value):
                self.validate(item, schema.get("items", {}), "{}[{}]".format(label, index), depth + 1)
        if isinstance(value, dict):
            if any(not isinstance(key, str) for key in value):
                raise StudioApiPlanningError("{} requires string property names.".format(label))
            if len(value) < schema.get("minProperties", 0) or len(value) > schema.get("maxProperties", math.inf):
                raise StudioApiPlanningError("{} exceeds its published property count.".format(label))
            missing = set(schema.get("required", [])) - set(value)
            if missing:
                raise StudioApiPlanningError("{} is missing {}.".format(label, ", ".join(sorted(missing))))
            properties = schema.get("properties", {})
            for key, item in value.items():
                child = properties.get(key, schema.get("additionalProperties", True))
                self.validate(item, child, label + "." + key, depth + 1)

    def revision_domain(self, operation_id, path, body=None):
        operation = self.operation(operation_id)
        project = path.get("project_id")
        if not project:
            return None
        if operation_id in ("getClipWaveform", "editClipSamples", "undoClipSampleEdit"):
            return ("source", project, path.get("clip_id"))
        if operation_id in MIX_OPERATIONS:
            return ("mix", project)
        # updateLane's If-Match is the timeline revision, or for its mix fields
        # the mix revision ("mix-<n>" / body expected_mix_revision).
        if operation_id == "updateLane" and isinstance(body, dict) and body.get("expected_mix_revision") is not None:
            return ("mix", project)
        if "/automation/{envelope_id}" in operation["path"]:
            return ("envelope", project, path.get("envelope_id"))
        if operation_id in ("getTimingMap", "setTimingMap", "undoTimingMap", "setProjectTempo"):
            return ("timing", project)
        if operation_id in ("seek", "setLoop"):
            return ("timing", project) if isinstance(body, dict) and any(key in body for key in ("tick", "start_tick", "end_tick", "timing_map_revision")) else None
        if any(parameter.get("name") in ("If-Match", "If-None-Match") for parameter in operation.get("parameters", [])):
            return ("timeline", project)
        return None

    def etag_for(self, operation_id, *, path=None, body=None):
        domain = self.revision_domain(operation_id, path or {}, body)
        with self._lock:
            return self.etags.get(domain)

    def seed_etag(self, operation_id, value, *, path=None, body=None):
        domain = self.revision_domain(operation_id, path or {}, body)
        if domain is None:
            raise StudioApiPlanningError("This operation has no published revision domain.")
        with self._lock:
            self.etags[domain] = _etag(value)

    def plan(self, operation_id, *, path=None, query=None, body=None, headers=None,
             idempotency_key=None, if_match=None, use_etag=True, require_revision=False):
        operation = self.operation(operation_id)
        path, query, headers = deepcopy(path or {}), deepcopy(query or {}), dict(headers or {})
        body = deepcopy(body)
        # A waveform ETag identifies source PCM, while this body also contains
        # timeline placement. It cannot validate a cached whole representation.
        if operation_id == "getClipWaveform":
            use_etag = False
            headers = {key: value for key, value in headers.items()
                       if not isinstance(key, str) or key.lower() != "if-none-match"}
        for name, value in list(headers.items()):
            if not isinstance(name, str) or re.fullmatch(r"[!#$%&'*+.^_`|~0-9A-Za-z-]+", name) is None:
                raise StudioApiPlanningError("Use a valid HTTP header name.")
            _set_header(headers, name, value)
        definitions = {}
        for parameter in operation.get("parameters", []):
            parameter = self._resolve(parameter)
            definitions[(parameter["in"], parameter["name"])] = parameter
        for location, values in (("path", path), ("query", query)):
            for name in values:
                if (location, name) not in definitions:
                    raise StudioApiPlanningError("Unknown {} parameter {} for {}.".format(location, name, operation_id))
            for (place, name), parameter in definitions.items():
                if place != location:
                    continue
                if name not in values or values[name] is None:
                    if parameter.get("required"):
                        raise StudioApiPlanningError("Missing {} parameter {}.".format(location, name))
                    values.pop(name, None)
                    continue
                self.validate(values[name], parameter.get("schema", {}), "{} parameter {}".format(location, name))
        uri = operation["path"]
        for name, value in path.items():
            uri = uri.replace("{" + name + "}", quote(str(value), safe=""))
        if "{" in uri or "}" in uri:
            raise StudioApiPlanningError("The operation has unresolved path parameters.")
        serialized = []
        for name, value in query.items():
            for item in value if isinstance(value, list) else [value]:
                if isinstance(item, (dict, list)):
                    raise StudioApiPlanningError("{} needs scalar query values.".format(name))
                serialized.append((name, "true" if item is True else "false" if item is False else str(item)))
        url = self.base_url + uri + ("?" + urlencode(serialized) if serialized else "")
        request_body = operation.get("requestBody")
        if request_body:
            request_body = self._resolve(request_body)
            if body is None and request_body.get("required"):
                raise StudioApiPlanningError("{} requires its JSON body (use {{}} for an empty body).".format(operation_id))
            if body is not None:
                content = request_body.get("content", {})
                if "application/json" not in content:
                    raise StudioApiPlanningError("This generated client supports the published JSON request body only.")
                self.validate(body, content["application/json"].get("schema", {}), "request body")
        elif body is not None:
            raise StudioApiPlanningError("{} does not accept a request body.".format(operation_id))
        if body is not None:
            try:
                json.dumps(body, allow_nan=False)
            except (TypeError, ValueError, OverflowError, RecursionError):
                raise StudioApiPlanningError("The request body must be finite JSON.") from None
            headers.setdefault("Content-Type", "application/json")
        headers.setdefault("Accept", BINARY_OPERATIONS.get(operation_id, "application/json"))
        method = operation["method"]
        domain = self.revision_domain(operation_id, path, body)
        if idempotency_key is not None:
            existing = _header(headers, "Idempotency-Key")
            if existing is not None and existing != idempotency_key:
                raise StudioApiPlanningError("Conflicting Idempotency-Key values describe different intents.")
            _set_header(headers, "Idempotency-Key", idempotency_key)
        if method in MUTATIONS and _header(headers, "Idempotency-Key") is None:
            headers["Idempotency-Key"] = str(uuid.uuid4())
        expected = None
        if isinstance(body, dict):
            for key in (("expectedRevision",) if domain and domain[0] == "envelope" else
                        ("timing_map_revision", "expected_revision") if domain and domain[0] == "timing" else
                        ("expected_revision",) if domain and domain[0] == "source" else
                        ("expected_mix_revision",) if domain and domain[0] == "mix" else ()):
                if body.get(key) is not None:
                    expected = mix_etag(body[key]) if key == "expected_mix_revision" else _etag(body[key])
                    break
        header_match = _header(headers, "If-Match")
        if if_match is not None and header_match is not None and _revision_value(_etag(if_match)) != _revision_value(_etag(header_match)):
            raise StudioApiPlanningError("Conflicting If-Match preconditions.")
        explicit = if_match if if_match is not None else header_match
        if operation_id == "updateLane" and explicit is not None and _revision_value(_etag(explicit)).startswith("mix-"):
            domain = ("mix", path.get("project_id"))
        if explicit is not None:
            explicit = _etag(explicit)
            if expected is not None and _revision_value(explicit) != _revision_value(expected):
                raise StudioApiPlanningError("If-Match and the body's expected revision disagree.")
        with self._lock:
            cached = self._cache.get(url)
            tag = self.etags.get(domain) if domain else None
            self._serial += 1
            serial = self._serial
            epoch = self._epochs.get(domain, 0)
        if ("header", "If-Match") in definitions:
            selected = explicit or expected or (tag if use_etag and not (domain and domain[0] == "mix") else None)
            if selected is not None:
                _set_header(headers, "If-Match", selected)
            elif require_revision or operation_id in ("editClipSamples", "undoClipSampleEdit"):
                raise StudioApiPlanningError("Read the resource revision before {}.".format(operation_id))
        elif explicit is not None:
            raise StudioApiPlanningError("{} does not declare an If-Match precondition.".format(operation_id))
        if use_etag and method == "GET" and cached and ("header", "If-None-Match") in definitions and _header(headers, "If-None-Match") is None:
            _set_header(headers, "If-None-Match", cached["etag"])
        for (location, name), parameter in definitions.items():
            if location == "header":
                value = _header(headers, name)
                if value is None and parameter.get("required"):
                    raise StudioApiPlanningError("Missing header {}.".format(name))
                if value is not None:
                    self.validate(value, parameter.get("schema", {}), "header " + name)
        return StudioApiRequest(operation_id, method, url, headers, body, domain, epoch, serial)

    @staticmethod
    def _project_of(request):
        match = re.match(r"^[a-z]+://[^/]+(?:/[^/]+)*?/projects/([^/?]+)", request.url)
        return unquote(match.group(1)) if match else None

    def timeline_stale(self, project_id):
        """True after a write bumped the timeline without returning its revision."""
        with self._lock:
            return project_id in self._timeline_stale

    def _settle_timeline(self, request, domain, adopted, data):
        """Keep the cached timeline ETag truthful after a successful write: adopt
        a returned revision, otherwise drop it so the next guarded timeline
        write starts from a fresh read (never a stale 412-bound revision)."""
        timeline_write = domain is not None and domain[0] == "timeline"
        if not timeline_write and request.operation_id not in TIMELINE_SIDE_EFFECT_OPERATIONS:
            return
        project = domain[1] if domain is not None else self._project_of(request)
        if not project:
            return
        key = ("timeline", project)
        if timeline_write and adopted:
            return
        if not timeline_write:
            # Fence in-flight timeline reads planned before this write.
            self._epochs[key] = self._epochs.get(key, 0) + 1
            self._invalidate_domain(key)
        revision = data.get("timelineRevision", data.get("timeline_revision")) if isinstance(data, dict) else None
        if isinstance(revision, str) and revision and not revision.startswith("mix-") and "\r" not in revision and "\n" not in revision:
            self.etags[key] = _etag(revision)
            self._timeline_stale.discard(project)
        else:
            self.etags.pop(key, None)
            self._invalidate_domain(key)
            self._timeline_stale.add(project)

    def _invalidate_domain(self, domain):
        for url in [url for url, value in self._cache.items() if value["domain"] == domain]:
            del self._cache[url]

    def send(self, request):
        if not isinstance(request, StudioApiRequest):
            raise TypeError("Send a retained StudioApiRequest.")
        if self.transport is None:
            raise RuntimeError("Inject a Studio API transport before calling operations.")
        if request.operation_id in NON_RETRYING_OPERATIONS:
            key = _header(request.headers, "Idempotency-Key")
            with self._lock:
                if key in self._sent_inputs:
                    raise StudioApiPlanningError("Live editor input is sent once and never retried.", "editor_input_not_retryable")
                self._sent_inputs[key] = None
                while len(self._sent_inputs) > 8192:
                    self._sent_inputs.pop(next(iter(self._sent_inputs)))
        mutation = request.method in MUTATIONS
        domain, write_epoch = request.revision_domain, None
        if mutation and domain is not None:
            with self._lock:
                self._epochs[domain] = self._epochs.get(domain, 0) + 1
                write_epoch = self._epochs[domain]
                self._pending_writes[domain] = self._pending_writes.get(domain, 0) + 1
                self._invalidate_domain(domain)
        try:
            response = self.transport(request)
            if not isinstance(response, StudioApiResponse):
                raise TypeError("The Studio API transport must return StudioApiResponse.")
            if response.status >= 400:
                if response.status == 412 and domain is not None:
                    with self._lock:
                        self.etags.pop(domain, None)
                        self._invalidate_domain(domain)
                raise StudioApiError(response, request)
            if response.status == 304 and (request.operation_id in BINARY_OPERATIONS or request.operation_id in UNCHANGED_304_OPERATIONS):
                return StudioApiResponse(304, None, dict(response.headers))
            if response.status == 304:
                if request.operation_id == "getClipWaveform":
                    # Also fence requests planned by an earlier caller before a
                    # timeline edit: source-only 304 cannot prove clip geometry.
                    raise StudioApiPlanningError("A source-only waveform 304 cannot verify placement; re-read unconditionally.")
                with self._lock:
                    cached = self._cache.get(request.url)
                    if cached is None:
                        raise StudioApiPlanningError("A 304 response has no matching cached representation; re-read unconditionally.")
                    if cached["epoch"] != self._epochs.get(domain, 0):
                        raise StudioApiPlanningError("The cached representation changed while its conditional read was pending.")
                    return StudioApiResponse(304, deepcopy(cached["data"]), dict(cached["headers"], **response.headers), True)
            if not 200 <= response.status < 300:
                raise StudioApiError(response, request)
            tag = response.header("ETag")
            with self._lock:
                current_epoch = self._epochs.get(domain, 0)
                adopt = (domain is not None and (write_epoch == current_epoch if mutation else
                         request.cache_epoch == current_epoch and not self._pending_writes.get(domain, 0)) and
                         request.serial >= self._observation_serial.get(domain, 0))
                # A mix ETag ("mix-<n>") never becomes another domain's revision.
                adopted = bool(adopt and tag and (domain[0] == "mix") == _revision_value(tag).startswith("mix-"))
                if adopted:
                    self.etags[domain] = tag
                    self._observation_serial[domain] = request.serial
                    if domain[0] == "timeline":
                        self._timeline_stale.discard(domain[1])
                if mutation:
                    self._settle_timeline(request, domain, adopted, response.data)
                if (request.method == "GET" and request.operation_id != "getClipWaveform" and request.operation_id not in BINARY_OPERATIONS
                        and request.operation_id not in UNCHANGED_304_OPERATIONS
                        and tag and (domain is None or adopt)):
                    self._cache[request.url] = {"data": deepcopy(response.data), "headers": dict(response.headers),
                                                "etag": tag, "domain": domain, "epoch": current_epoch}
            return response
        finally:
            if mutation and domain is not None:
                with self._lock:
                    self._pending_writes[domain] = max(0, self._pending_writes.get(domain, 1) - 1)

    def _call_plan(self, operation_id, *, path=None, query=None, body=None, headers=None,
            idempotency_key=None, if_match=None, use_etag=True, require_revision=False):
        if operation_id in NON_RETRYING_OPERATIONS:
            # Fresh key per event, no retained intent (bounded plan capacity is
            # reserved for recoverable edits; input is never replayed).
            # A caller key (one per event) is honoured; a reused key is refused at send().
            return self.plan(operation_id, path=path, query=query, body=body,
                headers={k: v for k, v in (headers or {}).items() if str(k).lower() not in ("authorization", "idempotency-key")},
                idempotency_key=idempotency_key, use_etag=False)
        if self.operation(operation_id)["method"] not in MUTATIONS:
            return self.plan(operation_id, path=path, query=query, body=body, headers=headers,
                idempotency_key=idempotency_key, if_match=if_match, use_etag=use_etag,
                require_revision=require_revision)
        explicit_headers = {}
        for name, value in (headers or {}).items():
            if not isinstance(name, str):
                raise StudioApiPlanningError("Use a valid HTTP header name.")
            # Authentication belongs to the injected runtime transport, never
            # the retained intent or its input fingerprint.
            if name.lower() != "authorization":
                _set_header(explicit_headers, name.lower(), value)
        supplied = explicit_headers.pop("idempotency-key", None)
        if supplied is not None and idempotency_key is not None and supplied != idempotency_key:
            raise StudioApiPlanningError("Conflicting Idempotency-Key values describe different intents.")
        key = idempotency_key if idempotency_key is not None else supplied or str(uuid.uuid4())
        _set_header({}, "Idempotency-Key", key)
        intent = {"operation": operation_id, "path": path or {}, "query": query or {}, "body": body,
            "headers": explicit_headers, "if_match": if_match, "use_etag": use_etag,
            "require_revision": require_revision}
        try:
            fingerprint = hashlib.sha256(json.dumps(intent, sort_keys=True, separators=(",", ":"),
                allow_nan=False).encode()).hexdigest()
        except (TypeError, ValueError, OverflowError, RecursionError):
            raise StudioApiPlanningError("The retained request must be finite JSON.") from None
        with self._lock:
            retained = self._write_plans.get(key)
            if retained is not None:
                if retained["fingerprint"] != fingerprint:
                    raise StudioApiPlanningError("This idempotency key already belongs to a different request.",
                        "retained_request_mismatch")
                return deepcopy(retained["request"])
            if len(self._write_plans) >= self._write_plan_limit:
                raise StudioApiPlanningError("The retained request capacity is full; existing intents remain recoverable.",
                    "retained_request_capacity")
            request = self.plan(operation_id, path=path, query=query, body=body, headers=explicit_headers,
                idempotency_key=key, if_match=if_match, use_etag=use_etag,
                require_revision=require_revision)
            self._write_plans[key] = {"fingerprint": fingerprint, "request": deepcopy(request)}
            return request

    def call(self, operation_id, **kwargs):
        return self.send(self._call_plan(operation_id, **kwargs))

    def iter_pages(self, operation_id, *, path=None, query=None, max_pages=1000):
        """Yield intact pages with stable filters and a bounded opaque cursor."""
        query = deepcopy(query or {})
        seen, first_etag = set(), None
        for _ in range(max_pages):
            response = self.call(operation_id, path=path, query=query)
            data = response.data
            if not isinstance(data, dict) or not isinstance(data.get("data"), list) or not isinstance(data.get("pagination"), dict):
                raise StudioApiPlanningError("The list operation did not return its documented page envelope.")
            tag = response.header("ETag")
            if first_etag is None:
                first_etag = tag
            elif tag and first_etag != tag:
                raise StudioApiPlanningError("The paged resource changed revision between pages; re-read before editing.")
            yield response
            cursor = data["pagination"].get("nextCursor")
            more = data["pagination"].get("hasMore")
            if not isinstance(more, bool) or (cursor is None) == more:
                raise StudioApiPlanningError("The list operation returned inconsistent pagination metadata.")
            if cursor is None:
                return
            if not isinstance(cursor, str) or not cursor or cursor in seen:
                raise StudioApiPlanningError("The list operation returned an invalid or repeated cursor.")
            seen.add(cursor)
            query["cursor"] = cursor
        raise StudioApiPlanningError("The list exceeded its bounded page count.")
